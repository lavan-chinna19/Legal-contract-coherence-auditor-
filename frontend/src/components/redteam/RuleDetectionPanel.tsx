"use client";

import React from "react";
import { RedTeamCaseResponse } from "./types";
import { CheckCircle, ShieldAlert } from "lucide-react";

interface RuleDetectionPanelProps {
  caseResult: RedTeamCaseResponse;
}

export function RuleDetectionPanel({ caseResult }: RuleDetectionPanelProps) {
  const flags = caseResult.new_rule_flags || [];

  return (
    <div className="bg-slate-900/90 border border-slate-800 rounded-xl p-4 space-y-3">
      <div className="flex items-center justify-between border-b border-slate-800 pb-3">
        <div className="flex items-center gap-2">
          <ShieldAlert size={16} className="text-purple-400" />
          <h4 className="text-xs font-bold text-slate-100 tracking-wide">
            5. Deterministic Rule Checker Findings ({flags.length})
          </h4>
        </div>
        <span className="text-[11px] font-mono text-slate-400">
          CrossReferenceChecker (spaCy) &amp; DateLogicChecker (dateparser)
        </span>
      </div>

      {flags.length === 0 ? (
        <div className="bg-slate-950/50 border border-slate-800/80 rounded-lg p-4 text-center text-xs text-slate-400">
          <CheckCircle size={20} className="mx-auto mb-2 text-slate-500 opacity-60" />
          <p>No new rule violations generated by this scenario.</p>
          <p className="text-[11px] text-slate-500 mt-0.5">
            Expected for structural-only perturbations (P1, P2) and negative controls (P9).
          </p>
        </div>
      ) : (
        <div className="space-y-2.5 max-h-[300px] overflow-y-auto pr-1">
          {flags.map((flag, idx) => {
            const isHigh = flag.severity === "HIGH";
            return (
              <div
                key={`rule-flag-${flag.flag_id || idx}`}
                className={`p-3 rounded-lg border text-xs space-y-1.5 ${
                  isHigh
                    ? "bg-red-950/25 border-red-500/40 text-red-200"
                    : "bg-purple-950/25 border-purple-500/40 text-purple-200"
                }`}
              >
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2 font-mono font-bold text-[11px]">
                    <span
                      className={`px-1.5 py-0.5 rounded text-[10px] font-bold ${
                        isHigh
                          ? "bg-red-500/20 text-red-400 border border-red-500/30"
                          : "bg-purple-500/20 text-purple-300 border border-purple-500/30"
                      }`}
                    >
                      {flag.severity || "HIGH"}
                    </span>
                    <span>{flag.flag_type}</span>
                  </div>

                  {flag.clause_id && (
                    <span className="font-mono text-[10px] text-slate-400 bg-slate-900 px-1.5 py-0.5 rounded border border-slate-800">
                      Target: {flag.clause_id}
                    </span>
                  )}
                </div>

                <div className="font-semibold text-slate-200 text-xs">
                  {flag.title}
                </div>

                <p className="text-slate-300 leading-relaxed text-[11px]">
                  {flag.description}
                </p>

                {flag.evidence && Object.keys(flag.evidence).length > 0 && (
                  <div className="bg-slate-950/80 rounded p-2 border border-slate-800/80 text-[10px] font-mono text-slate-400 space-y-0.5">
                    <span className="text-slate-500 block font-semibold">Evidence Payload:</span>
                    {Object.entries(flag.evidence).map(([k, v]) => (
                      <div key={k} className="flex justify-between">
                        <span className="text-slate-500">{k}:</span>
                        <span className="text-slate-300">{String(v)}</span>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
